// Attach each result bout's closing moneylines (aligned to that bout's f1/f2 order) from the
// closing feed, so gradeCard's underdog check has the real line. Name-tolerant match.
function withClosingOdds(bouts, closingFights) {
  if (!closingFights || !closingFights.length) return bouts || [];
  return (bouts || []).map((b) => {
    const cf = closingFights.find((c) =>
      (namesMatch(c.f1, b.f1) && namesMatch(c.f2, b.f2)) || (namesMatch(c.f1, b.f2) && namesMatch(c.f2, b.f1)));
    if (!cf || cf.o1 == null || cf.o2 == null) return b;
    return namesMatch(cf.f1, b.f1) ? { ...b, o1: cf.o1, o2: cf.o2 } : { ...b, o1: cf.o2, o2: cf.o1 };
  });
}
// Turn one ESPN bout into a gradeable result, or null if it isn't decided yet.
// A bout is decided when a fighter has a `win` outcome (winnerFighterSlug can be
// null for a late replacement) or the method reads draw/no-contest.
// Bucket a raw method string into the pick vocabulary (mirrors the app's methodBucketOf).
function methodBucket(s) {
  s = String(s || "").toLowerCase();
  if (/sub/.test(s)) return "Submission";
  if (/dec/.test(s)) return "Decision";
  if (/ko|tko|knockout|stoppage|punch|kick|elbow|knee|slam/.test(s)) return "KO/TKO";
  return null;
}
function boutToResult(b) {
  if (!b || b.isCancelled) return null;
  const fs = b.fighters || [];
  if (fs.length !== 2) return null;
  const f1 = fs[0].fighterName, f2 = fs[1].fighterName;
  if (!f1 || !f2) return null;
  const win = (b.winnerFighterSlug && fs.find(f => f.fighterSlug === b.winnerFighterSlug)) ||
              fs.find(f => f.outcome === "win");
  // resultTime ("4:49") comes straight from ESPN via scripts/fetch-espn-live.cjs
  // (see its header comment) but was getting dropped here — btResolveResult had
  // no time to parse and fell back to assuming every finish ran the full round,
  // which mis-grades a TOTAL (over/under rounds) bet whose line falls in the
  // second half of the round the fight actually ended in.
  if (win) return { f1, f2, winner: win.fighterName, method: b.method || "", round: b.resultRound || null, time: b.resultTime || null, voided: false };
  const drawNC = /draw|no\s*contest|^\s*nc\s*$/i.test(b.method || "") || fs.every(f => f.outcome === "draw");
  if (drawNC) return { f1, f2, winner: null, method: b.method || "", round: b.resultRound || null, time: b.resultTime || null, voided: true };
  return null;   // still pending
}
// Read the live ESPN feed from the bundle and return the "focus" card — the one in
// progress (or, between cards, the most recently started card that has results) —
// as gradeable bouts. This lets the leaderboard score a card AS IT HAPPENS, without
// waiting for the end-of-card results sweep. Returns null when nothing has results.
async function loadFocusEvent(env, url) {
  let feed;
  try {
    const r = await env.ASSETS.fetch(new Request(new URL("/data/event.json", url)));
    if (!r.ok) return null;
    feed = await r.json();
  } catch { return null; }
  const events = (Array.isArray(feed && feed.data) ? feed.data : []).slice();
  // Fold in the held card. event.json holds UPCOMING cards only — a finished card is
  // DELETED from it, not marked completed — so once the feed refreshed there was no
  // card left here with results at all, and this returned null: /matchup stopped
  // folding results into its fight-info dropdowns and kept showing the tale of the
  // tape. loadHeldCard applies the 34h window, so this only ever adds a card the rest
  // of the site is still featuring.
  const held = await loadHeldCard(env, url, Date.now());
  if (held && !events.some(e => e && e.slug === held.slug)) events.push(held);
  // Only a card that actually has results can be the focus, so we don't need a
  // start-time filter (a future card has no decided bouts). This also sidesteps the
  // prelims-vs-main-card start-time ambiguity.
  const withResults = events
    .map(ev => ({ ev, bouts: (ev.bouts || []).map(boutToResult).filter(Boolean) }))
    .filter(x => x.bouts.length);
  if (!withResults.length) return null;
  // Prefer a live card; otherwise the most recently started card that has results.
  withResults.sort((a, b) => (Date.parse(b.ev.startsAt || 0) || 0) - (Date.parse(a.ev.startsAt || 0) || 0));
  const pick = withResults.find(x => x.ev.status === "live") || withResults[0];
  const total = (pick.ev.bouts || []).filter(b => b && !b.isCancelled && (b.fighters || []).length === 2).length;
  return {
    slug: pick.ev.slug,
    name: pick.ev.title || pick.ev.espnName || pick.ev.shortTitle || pick.ev.slug,
    date: (pick.ev.startsAt || "").slice(0, 10),
    live: pick.ev.status === "live",
    bouts: pick.bouts, decided: pick.bouts.length, total,
  };
}
// Public live-results feed for the FREE pages. The in-progress card's decided bouts,
// distilled to {f1,f2,winner,method,round,voided} straight from the same focus-card
// grader the leaderboard uses — so /matchup can fold each result into its fight-info
// dropdown and /pickem can grade the picks card live, without either page re-parsing
// the ESPN feed. No auth: it's the same public event data every visitor already sees.
// no-store so a poll always gets the freshest card, never an edge-cached snapshot.
async function handleLiveResults(env, url) {
  const noStore = { "Cache-Control": "no-store" };
  const focus = await loadFocusEvent(env, url);
  if (!focus) return json({ slug: null, live: false, final: false, decided: 0, total: 0, bouts: [] }, 200, noStore);
  const final = focus.total > 0 && focus.decided >= focus.total;
  // mb = the method bucketed into the pick vocabulary (KO/TKO | Submission | Decision),
  // so /pickem can grade method hits; the raw `method` stays for /matchup's display.
  const bouts = focus.bouts.map((b) => ({ ...b, mb: methodBucket(b.method) }));
  return json({
    slug: focus.slug, name: focus.name, date: focus.date,
    live: focus.live, final, decided: focus.decided, total: focus.total, bouts,
  }, 200, noStore);
}
// CARD_HOLD_MS (how long a finished card keeps the featured/pickable slot) is imported
// from pages.js so the Worker has exactly one copy — /matchup, /pickem and
// /api/live-results must roll over on the same tick or the surfaces disagree, which is
// the bug this whole mechanism exists to prevent.

// A bout is settled once the feed carries a result (draws/NCs have no winner slug).
function heldBoutSettled(b) {
  return !!(b && (b.isCancelled || b.winnerFighterSlug || b.method ||
    String(b.status || "").toLowerCase() === "completed"));
}

// The most recently completed card still inside its hold window, read from
// data/event-recent.json (the workflow's past-events fetch, which keeps finished
// cards WITH results after event.json has dropped them). Returns null when there
// is no such card, or when the file is missing/unreadable — in which case callers
// fall back to the next scheduled card, i.e. the pre-hold behaviour.
async function loadHeldCard(env, url, now) {
  let recent;
  try {
    const r = await env.ASSETS.fetch(new Request(new URL("/data/event-recent.json", url)));
    if (!r.ok) return null;
    recent = await r.json();
  } catch { return null; }
  const t = (e) => Date.parse((e && (e.startsAt || e.eventDate)) || 0) || 0;
  return (Array.isArray(recent && recent.data) ? recent.data : [])
    // Only a fully settled card may hold: a half-synced copy must never displace
    // the live feed mid-card.
    .filter((e) => e && (e.bouts || []).length && e.status === "completed"
      && e.bouts.every(heldBoutSettled)
      && t(e) > 0 && t(e) <= now && t(e) + CARD_HOLD_MS >= now)
    .sort((a, b) => t(b) - t(a))[0] || null;
}

// The next upcoming card to PICK — the soonest event that hasn't finished, with its
// bouts (main event first). Powers the standalone /pickem page. Returns a compact
// shape: names + slugs (for photos) + card position + rounds, and the prelims lock.
async function loadUpcomingCard(env, url) {
  let feed;
  try {
    const r = await env.ASSETS.fetch(new Request(new URL("/data/event.json", url)));
    if (!r.ok) return null;
    feed = await r.json();
  } catch { return null; }
  const now = Date.now();
  // A finished card holds this slot for 34h after its main-card start, matching the
  // app's CARD_HOLD_MS — so /pickem keeps showing last night's scored picks through
  // Sunday and hands off Monday morning, in step with every other surface.
  //
  // The hold has to come from event-recent.json, NOT from a wider window here: once a
  // card is over the upstream feed removes it from event.json outright rather than
  // marking it completed, so there is nothing left for a window to keep.
  const held = await loadHeldCard(env, url, now);
  // Select the SAME card the app's pickFeaturedRawEvent keeps featured, so /pickem never
  // jumps to the next event before the rest of the app does. Drop finished (completed)
  // cards, and keep a card current for 10h after its main-card start (CARD_RUNTIME_MS —
  // a long night plus the immediate aftermath) before handing off to the next one. The
  // old 6h-from-start grace is what moved /pickem on ~4h early.
  const CARD_RUNTIME_MS = 10 * 3600 * 1000;
  const events = (Array.isArray(feed && feed.data) ? feed.data : [])
    .filter(ev => ev && (ev.bouts || []).length && ev.status !== "completed");
  if (!events.length && !held) return null;
  const byStart = events.slice().sort((a, b) => (Date.parse(a.startsAt || 0) || 0) - (Date.parse(b.startsAt || 0) || 0));
  const ev = held || byStart.find(e => (Date.parse(e.startsAt || 0) || 0) + CARD_RUNTIME_MS >= now) || byStart[byStart.length - 1];
  const bouts = (ev.bouts || [])
    .filter(b => b && !b.isCancelled && (b.fighters || []).length === 2)
    .sort((a, b) => (a.boutOrder || 0) - (b.boutOrder || 0))
    .map((b, i) => {
      const f = b.fighters;
      // Once a bout is decided, carry its result so the client can render a graded
      // "results" share sheet (method bucketed to the pick vocabulary).
      const r = boutToResult(b);
      const res = r ? { winner: r.winner, method: methodBucket(r.method), round: r.round, voided: !!r.voided } : null;
      return {
        id: b.id || (ev.slug + "-" + i),
        f1: f[0].fighterName, f2: f[1].fighterName,
        s1: f[0].fighterSlug || null, s2: f[1].fighterSlug || null,
        section: b.cardSection || "", pos: b.cardPosition || "",
        wc: String(b.weightClass || "").replace(/\s*bout\s*$/i, "").trim(),
        rounds: b.numberOfRounds || 3, title: !!b.titleBout, res,
      };
    });
  const prelimsAt = ev.prelimsStartsAt || ev.startsAt || null;
  const final = bouts.length > 0 && bouts.every((x) => x.res);
  return {
    slug: ev.slug,
    name: ev.title || ev.espnName || ev.shortTitle || ev.slug,
    date: (ev.startsAt || "").slice(0, 10),
    prelimsAt, final,
    locked: prelimsAt ? now >= Date.parse(prelimsAt) : false,
    bouts,
  };
}
