// Attribution + commission bookkeeping for one paid invoice, called from the Stripe
// webhook. `isFirst` = this invoice's billing_reason is subscription_create (Stripe
// fires this on the VERY FIRST invoice of a subscription — reliable, not inferred).
async function recordPartnerInvoice(env, email, amountCents, isFirst, invoiceId) {
  const ref = await getReferral(env, email);
  if (!ref || !ref.partnerToken) return;   // not a referred customer — nothing to do
  const partner = await partnerByToken(env, ref.partnerToken);
  if (!partner) return;   // promo/referral pointed at a partner that no longer exists
  const pct = isFirst ? 50 : tierPctFor(partner, partner.referralCount || 0);
  const commissionCents = Math.round(amountCents * pct / 100);
  partner.lifetimeRevenueCents = (partner.lifetimeRevenueCents || 0) + amountCents;
  partner.lifetimeCommissionCents = (partner.lifetimeCommissionCents || 0) + commissionCents;
  if (isFirst) {
    const before = partner.referralCount || 0;
    partner.referralCount = before + 1;
    partner.activeCount = (partner.activeCount || 0) + 1;
    // $25 bonus per 10 paid referrals — crossing a multiple of 10, not "referral #10,
    // #20 exactly", so it still fires correctly if two checkouts land in one webhook
    // burst (Math.floor comparison handles any jump, not just +1).
    const crossed = Math.floor(partner.referralCount / 10) - Math.floor(before / 10);
    if (crossed > 0) {
      const bonusCents = crossed * 2500;
      partner.lifetimeCommissionCents += bonusCents;
      await addLedgerEntry(env, partner.token, { invoiceId: invoiceId + ":bonus", email, amountCents: 0, pct: null, commissionCents: bonusCents, kind: "bonus", date: Date.now() });
    }
  }
  await putPartner(env, partner);
  await addLedgerEntry(env, partner.token, { invoiceId, email, amountCents, pct, commissionCents, kind: isFirst ? "first" : "recurring", date: Date.now() });
}

/* ───────────────────────────── binary <-> base64 (W-9 uploads) ─────────────────
 * KV values are strings, so an uploaded file gets base64-encoded before storage.
 * Chunked to avoid String.fromCharCode.apply blowing the call stack on a multi-MB
 * file — the naive one-liner works fine for small buffers but throws on larger
 * ones in some runtimes. */
function arrayBufferToBase64(buf) {
  const bytes = new Uint8Array(buf);
  let binary = "";
  const chunkSize = 0x8000;
  for (let i = 0; i < bytes.length; i += chunkSize) {
    binary += String.fromCharCode.apply(null, bytes.subarray(i, i + chunkSize));
  }
  return btoa(binary);
}
function base64ToArrayBuffer(b64) {
  const binary = atob(b64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes.buffer;
}

/* ─────────────────────────────────── Stripe ────────────────────────────────── */
function formEncode(obj, prefix = "", out = []) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}[${k}]` : k;
    if (v && typeof v === "object") formEncode(v, key, out);
    else out.push(`${encodeURIComponent(key)}=${encodeURIComponent(v)}`);
  }
  return out.join("&");
}
async function stripe(env, path, method = "GET", body = null) {
  const res = await fetch("https://api.stripe.com/v1/" + path, {
    method,
    headers: { Authorization: "Bearer " + env.STRIPE_SECRET_KEY, "Content-Type": "application/x-www-form-urlencoded" },
    body: body ? formEncode(body) : undefined,
  });
  const data = await res.json();
  if (!res.ok) throw new Error("stripe " + path + ": " + (data.error?.message || res.status));
  return data;
}
// promotionCodeId: a resolved Stripe promotion_code ID ("promo_...") from a
// partner's trackable ?ref= link (see resolvePromoIdForRef / handleCheckout).
// When present it's pre-applied and allow_promotion_codes is dropped — Stripe
// rejects a session that sets both. A visitor who typed a DIFFERENT partner's
// code by hand instead of using their link still gets the discount either way;
// they just don't get pre-filled into a field they'd have needed to find.
async function createCheckout(env, email, customerId, promotionCodeId) {
  const params = {
    mode: "subscription",
    "line_items": { "0": { price: env.STRIPE_PRICE_ID, quantity: 1 } },
    success_url: env.SITE_URL + "/api/checkout/success?session_id={CHECKOUT_SESSION_ID}",
    cancel_url: env.SITE_URL + "/subscribe?canceled=1",
    client_reference_id: normEmail(email),
  };
  if (promotionCodeId) params.discounts = { "0": { promotion_code: promotionCodeId } };
  else params.allow_promotion_codes = "true";
  if (customerId) params.customer = customerId; else params.customer_email = normEmail(email);
  const s = await stripe(env, "checkout/sessions", "POST", params);
  return s.url;
}
async function markSubscribed(env, email, customerId, subscribed, extra = {}) {
  const e = normEmail(email);
  const u = (await getUser(env, e)) || { email: e, createdAt: Date.now() };
  // partnerComp overrides whatever Stripe is reporting: Stripe only knows about
  // a REAL subscription this email may separately have/had, and has no idea the
  // person is also comped for being an active partner (see grantPartnerComp /
  // revokePartnerComp near the partner-admin routes). Without this, a comped
  // partner who happens to also cancel a real subscription of their own would
  // get silently un-comped by this exact webhook path. Revoking the comp itself
  // only ever happens in revokePartnerComp, never here.
  u.subscribed = u.partnerComp ? true : !!subscribed;
  if (customerId) { u.stripeCustomerId = customerId; await linkCustomer(env, customerId, e); }
  Object.assign(u, extra);
  await putUser(env, e, u);
  return u;
}
// Partner free-premium comp — granted on /admin/partners/add, revoked on
// /admin/partners/remove. Kept as a separate boolean from `subscribed` (rather
// than just flipping `subscribed` directly) specifically so markSubscribed
// above can tell "comped" apart from "genuinely paying" and never clobber one
// with the other.
async function grantPartnerComp(env, email) {
  const e = normEmail(email);
  const u = (await getUser(env, e)) || { email: e, createdAt: Date.now() };
  u.partnerComp = true;
  u.subscribed = true;
  await putUser(env, e, u);
}
async function revokePartnerComp(env, email) {
  const e = normEmail(email);
  const u = await getUser(env, e);
  if (!u) return;
  u.partnerComp = false;
  // Don't just flip subscribed to false — re-derive it from Stripe's own truth
  // so a partner who's ALSO a genuine paying customer keeps their real access;
  // only the free comp goes away. No stripeCustomerId on file means they never
  // had a real subscription tied to this email, so false is correct outright.
  let realSub = false;
  if (u.stripeCustomerId) {
    try {
      const found = await stripe(env, "subscriptions?customer=" + encodeURIComponent(u.stripeCustomerId) + "&status=active&limit=1", "GET");
      realSub = !!(found.data && found.data.length);
    } catch (err) {
      // Stripe hiccup — leave subscribed as it was rather than guess wrong and
      // cut off someone who may genuinely be paying.
      realSub = u.subscribed;
    }
  }
  u.subscribed = realSub;
  await putUser(env, e, u);
}
async function verifyStripeSig(payload, header, secret) {
  // header: t=timestamp,v1=signature (HMAC-SHA256 of `${t}.${payload}`)
  const parts = Object.fromEntries((header || "").split(",").map(p => p.split("=")));
  if (!parts.t || !parts.v1) return false;
  if (Math.abs(Date.now() / 1000 - Number(parts.t)) > 300) return false; // 5-min tolerance
  const expected = await hmacHex(enc.encode(secret), `${parts.t}.${payload}`);
  return timingSafeEq(expected, parts.v1);
}

/* ─────────────────────────────────── email (Resend) ────────────────────────── */
async function sendEmail(env, to, subject, html, replyTo, headers) {
  if (!env.RESEND_API_KEY) throw new Error("email not configured");
  const payload = { from: env.FROM_EMAIL, to, subject, html };
  if (replyTo) payload.reply_to = replyTo;
  if (headers) payload.headers = headers;
  const res = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: { Authorization: "Bearer " + env.RESEND_API_KEY, "Content-Type": "application/json" },
    body: JSON.stringify(payload),
  });
  if (!res.ok) throw new Error("email send failed: " + (await res.text()));
}

// Contact form → email to CONTACT_TO, with reply-to set to the sender so a reply
// goes straight back to them. Honeypot ("company") silently drops bot spam.
async function handleContact(request, env) {
  let b = {};
  try { b = await request.json(); } catch {}
  if (b.company) return json({ ok: true });   // honeypot filled → pretend success, drop
  const name = String(b.name || "").trim();
  const email = String(b.email || "").trim();
  const message = String(b.message || "").trim();
  if (!name || !email || !message) return json({ error: "Please add your name, email, and a message." }, 400);
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) return json({ error: "Please enter a valid email address." }, 400);
  if (message.length > 5000) return json({ error: "Please keep your message under 5,000 characters." }, 400);
  const esc = (s) => String(s).replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c]));
  const bodyHtml = `<p><strong>From:</strong> ${esc(name)} &lt;${esc(email)}&gt;</p><p><strong>Message:</strong></p><p>${esc(message).replace(/\n/g, "<br>")}</p>`;
  try {
    await sendEmail(env, CONTACT_TO, `GillyLab contact — ${name}`, bodyHtml, email);
    return json({ ok: true });
  } catch {
    return json({ error: "Couldn't send your message right now. Please email " + CONTACT_TO + " directly." }, 500);
  }
}

