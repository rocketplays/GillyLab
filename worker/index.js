// Log a bet. The server owns the lock and CLV eligibility.
async function handleBetsAdd(request, env, url) {
  const s = await betsSession(request, env);
  if (!s) return json({ error: "unauthorized" }, 401);
  const body = await readBody(request);
  const kind = body.kind === "manual" ? "manual" : "tracked";
  const odds = parseInt(body.odds, 10);
  const stake = Math.max(0.1, Math.min(1000, Number(body.stake) || 1));
  if (!isFinite(odds) || odds === 0) return json({ error: "Enter the odds you got." }, 400);
  // Where they placed it. Free text, optional — a label only, nothing keys off it.
  const book = String(body.book || "").slice(0, 40).trim();
  const now = Date.now();
  const list = await btGetBets(env, s.email);
  if (list.length >= BT_MAX) return json({ error: "Bet log is full." }, 400);

  let rec;
  if (kind === "manual") {
    const match = String(body.match || "").slice(0, 160), pick = String(body.pick || "").slice(0, 160);
    if (!match || !pick) return json({ error: "Fill in the matchup and your pick." }, 400);
    // Self-reported: never verified, never CLV, user settles it.
    rec = { id: "b" + now + Math.random().toString(36).slice(2, 7), kind: "manual", verified: false,
      market: "CUSTOM", pick, match, odds, stake, book, status: "pending", ts: now, createdAt: now, editable: true };
  } else if (body.market === "PARLAY") {
    // Every leg must resolve to a live bout on ONE event, and none may be decided.
    // A parlay never earns CLV — there's no closing line for a combined price.
    const legs = Array.isArray(body.legs) ? body.legs.slice(0, 12) : [];
    if (legs.length < 2) return json({ error: "A parlay needs at least two legs." }, 400);
    const out = [];
    let evSlug = null, evStartsAt = null;
    for (const l of legs) {
      const hit = await btFindBout(env, url, String(l.fightId || ""));
      if (!hit) return json({ error: "One of those fights isn't on an upcoming card." }, 400);
      if (evSlug && hit.ev.slug !== evSlug) return json({ error: "Every leg has to be on the same event." }, 400);
      evSlug = hit.ev.slug; evStartsAt = hit.ev.startsAt;
      if (await btBoutDecided(env, url, hit)) return json({ error: "One of those fights has already finished.", locked: true }, 403);
      const lo = parseInt(l.odds, 10);
      if (!isFinite(lo) || lo === 0) return json({ error: "A leg is missing its odds." }, 400);
      out.push({ fightId: hit.id, market: String(l.market || "ML").slice(0, 16),
        params: l.params && typeof l.params === "object" ? l.params : {},
        pick: String(l.pick || "").slice(0, 160), match: String(l.match || "").slice(0, 160), odds: lo });
    }
    // Mirror the parlay builder's correlation rule (PL_PAIRABLE in index.html):
    // within ONE fight only the moneyline and the rounds O/U can be combined —
    // method and round props overlap the moneyline and each other, so multiplying
    // them can't price the overlap and no book would take it. The slip enforces
    // this before handing legs over; re-check it here so the rule doesn't rest on
    // the client being honest.
    const PAIRABLE = { ML: 1, TOTAL: 1 };
    const seenByFight = {};
    for (const l of out) {
      const prev = seenByFight[l.fightId] || [];
      if (prev.length) {
        if (!PAIRABLE[l.market] || prev.some((m) => !PAIRABLE[m]))
          return json({ error: "On one fight, only a moneyline and a rounds O/U can be parlayed." }, 400);
        if (prev.indexOf(l.market) !== -1)
          return json({ error: "You already have that market on this fight." }, 400);
      }
      seenByFight[l.fightId] = prev.concat(l.market);
    }
    rec = {
      id: "b" + now + Math.random().toString(36).slice(2, 7), kind: "tracked", verified: true,
      market: "PARLAY", evSlug, legs: out,
      pick: out.length + "-leg parlay", match: String(body.match || "").slice(0, 160),
      priced: false, clvOk: false, noClv: "parlays don't count toward CLV",
      odds, stake, book, ts: Date.parse(evStartsAt) || now, createdAt: now, editable: true,
    };
  } else {
    const hit = await btFindBout(env, url, String(body.fightId || ""));
    if (!hit) return json({ error: "That fight isn't on an upcoming card." }, 400);
    if (await btBoutDecided(env, url, hit)) return json({ error: "That fight has already finished.", locked: true }, 403);
    const segAt = Date.parse(hit.segAt);
    // Once a segment starts, its closing line is already captured — the bet still
    // grades, it just can't earn CLV. Server-decided, so the client can't fake it.
    const clvOk = !(isFinite(segAt) && now >= segAt);
    const noClv = clvOk ? null : (hit.section === "main" ? "main card has started" : "prelims already started");
    rec = {
      id: "b" + now + Math.random().toString(36).slice(2, 7), kind: "tracked", verified: true,
      fightId: hit.id, evSlug: hit.ev.slug,
      market: String(body.market || "ML").slice(0, 16),
      pick: String(body.pick || "").slice(0, 160), match: String(body.match || "").slice(0, 160),
      params: body.params && typeof body.params === "object" ? body.params : {},
      priced: !!body.priced, closeSide: body.closeSide === 2 ? 2 : 1,
      clvOk, noClv, odds, stake, book, ts: Date.parse(hit.ev.startsAt) || now,
      createdAt: now, editable: clvOk,
    };
  }
  list.push(rec);
  await btPutBets(env, s.email, list);
  return json({ ok: true, bet: rec });
}

// Settle a SELF-REPORTED bet. Tracked bets are graded from the result and can
// never be settled by hand — that's what keeps the verified numbers honest.
// Freeze a tracked bet's auto-graded outcome, permanently. The client grades (only
// it has FIGHT_HISTORY, the odds history and the per-market rules) and posts the
// result here the first time a bet settles; from then on it never needs re-deriving.
// WRITE-ONCE by design: a stored grade is never overwritten, so a later run that
// can't resolve the fight — because the card has aged out of every result feed —
// cannot quietly downgrade a settled bet back to pending.
async function handleBetsGrade(request, env) {
  const s = await betsSession(request, env);
  if (!s) return json({ error: "unauthorized" }, 401);
  const body = await readBody(request);
  const status = String(body.status == null ? "" : body.status).trim().toLowerCase();
  if (["won", "lost", "push", "void"].indexOf(status) === -1) {
    return json({ error: 'bad status: "' + String(body.status).slice(0, 40) + '"' }, 400);
  }
  const list = await btGetBets(env, s.email);
  const b = list.find((x) => x.id === body.id);
  if (!b) return json({ error: "not found" }, 404);
  if (b.kind !== "tracked") return json({ error: "only tracked bets grade automatically" }, 403);
  if (b.graded && b.graded.status) return json({ ok: true, already: true });
  const num = (v) => (typeof v === "number" && isFinite(v) ? v : null);
  b.graded = {
    status,
    clv: num(body.clv), closeOdds: num(body.closeOdds), effOdds: num(body.effOdds),
    legStatuses: Array.isArray(body.legStatuses) ? body.legStatuses.slice(0, 24).map((x) => String(x).slice(0, 12)) : null,
    legsIn: num(body.legsIn), legsLive: num(body.legsLive),
    at: Date.now(),
  };
  await btPutBets(env, s.email, list);
  return json({ ok: true });
}

// ── bet leaderboard + public player profile (subscriber-visible, mirrors pick'em) ──
// GRADE ON READ. The board and profiles grade every un-frozen bet here, from the same
// result + closing-odds feeds pick'em uses, so they reflect results the moment they land
// — no waiting for the bet's owner to open the tracker and freeze it. A bet that IS
// already frozen wins (its stored grade is authoritative). This path NEVER writes: it's
// display only, so a grading slip can't corrupt a stored record the way a bad freeze
// would — the owner's own client still writes the permanent grade via /api/bets/grade.
// VERIFIED ONLY: self-reported (manual) bets never touch the board.
const btRound1 = (x) => (x == null || !isFinite(x)) ? null : Math.round(x * 10) / 10;
// A per-bet profit rounded to 1dp reads wrong the moment the stake itself isn't
// a whole tenth of a unit — a 0.25u loss showed as "-0.3u", a 0.75u loss as
// "-0.8u" (both real reports). Aggregates (ROI/CLV points/summed units) are
// still fine at 1dp since those are sums across many bets, not one exact
// number a person just typed in; only the per-bet profit needs the finer grain.
const btRound2 = (x) => (x == null || !isFinite(x)) ? null : Math.round(x * 100) / 100;
const btLastName = (s) => String(s || "").trim().split(/\s+/).pop().toLowerCase();
function btMethodCat(m) {
  m = String(m || "");
  if (/sub/i.test(m)) return "SUB";
  if (/dec/i.test(m)) return "DEC";
  if (/ko|tko|knockout|stoppage|doctor|retire/i.test(m)) return "KO";
  return "DEC";
}
// "F1 vs F2 · Event" -> ["F1", "F2"] (short/last names, in the bet's side order).
function btMatchNames(match) {
  const head = String(match || "").split("·")[0].trim();
  const parts = head.split(/\s+vs\.?\s+/i);
  return parts.length === 2 && parts[0] && parts[1] ? [parts[0].trim(), parts[1].trim()] : null;
}
// Resolve a bout result relative to (a,b) = the bet's f1/f2, from the combined result
// events (finalized archive + live/recent event feeds). Last-name pairing, scoped to the
// event — the same match the app's archive path uses. null while still pending.
function btResolveResult(events, evSlug, a, b) {
  const la = btLastName(a), lb = btLastName(b);
  for (const ev of (events || [])) {
    if (evSlug && ev.slug && ev.slug !== evSlug) continue;
    for (const bt of (ev.bouts || [])) {
      const p1 = btLastName(bt.f1), p2 = btLastName(bt.f2);
      const straight = p1 === la && p2 === lb, crossed = p1 === lb && p2 === la;
      if (!straight && !crossed) continue;
      const m = String(bt.method || "");
      const isNC = /no contest|\bnc\b/i.test(m);
      const isDraw = /^draw/i.test(m) || (!!bt.voided && !isNC);
      let win = null;
      if (!bt.voided && bt.winner && !isDraw && !isNC) {
        const lw = btLastName(bt.winner);
        win = lw === la ? 1 : lw === lb ? 2 : null;
      }
      // Mirrors the client's btFightResult: use the actual finish time when this
      // bout carries one (bt.time, "M:SS" — now passed through by boutToResult),
      // and only fall back to assuming a full round when it doesn't (the archive
      // path, pickem-results.json, doesn't record one). Getting this wrong only
      // matters for a TOTAL (over/under rounds) bet whose line sits in the second
      // half of the round the fight actually ended in.
      const tm = /(\d+):(\d+)/.exec(String(bt.time || ""));
      const endSec = tm ? (+tm[1] * 60 + +tm[2]) : 300;
      return { win, methodCat: btMethodCat(m), round: Number(bt.round) || 1, endSec, isDraw, isNC };
    }
  }
  return null;
}
// The bet's closing moneyline for `side` (1/2), from odds-closing.json.
function btCloseFor(closing, a, b, side) {
  const la = btLastName(a), lb = btLastName(b);
  for (const c of (closing || [])) {
    if (c.o1 == null || c.o2 == null) continue;
    const p1 = btLastName(c.f1), p2 = btLastName(c.f2);
    if (p1 === la && p2 === lb) return side === 2 ? c.o2 : c.o1;
    if (p1 === lb && p2 === la) return side === 2 ? c.o1 : c.o2;
  }
  return null;
}
const btImplied = (o) => o < 0 ? (-o) / ((-o) + 100) : 100 / (o + 100);
const btClvPts = (yours, close) => Math.round((btImplied(close) - btImplied(yours)) * 1000) / 10;
const btAm2Dec = (o) => o > 0 ? (o / 100 + 1) : (100 / -o + 1);
const btDec2Am = (d) => d >= 2 ? Math.round((d - 1) * 100) : -Math.round(100 / (d - 1));
const btCombineOdds = (list) => btDec2Am(list.reduce((p, o) => p * btAm2Dec(o), 1));
// Per-market win rule, ported verbatim from the app's btGradeWin. tr is read only in the
// decision branch, where a decision's ending round IS the scheduled rounds — so callers
// pass R.round for tr and no scheduled-rounds lookup is needed.
function btGradeWin(market, P, R, tr) {
  P = P || {};
  if (market === "ML") return R.win === P.side;
  if (market === "METHOD") return (P.side === "any" || R.win === P.side) && R.methodCat === P.methodCat;
  if (market === "ENDROUND") { const fin = R.methodCat !== "DEC" && R.round === P.round; const methOK = !P.meth || P.meth === "ANY" || R.methodCat === P.meth; return fin && methOK && (P.side === "any" || R.win === P.side); }
  if (market === "TOTAL") { const sec = R.methodCat === "DEC" ? tr * 300 : ((R.round - 1) * 300 + R.endSec); const over = sec > (Math.floor(P.line) * 300 + 150); return P.ou === "O" ? over : !over; }
  if (market === "ROUNDSTART") { const s = R.methodCat === "DEC" ? (P.round <= tr) : (P.round <= R.round); return P.yn === "Y" ? s : !s; }
  if (market === "DISTANCE") { const went = R.methodCat === "DEC"; return P.yn === "Y" ? went : !went; }
  if (market === "INSIDE") return R.win === P.side && R.methodCat !== "DEC";
  if (market === "WINRDS") { if (R.win !== P.side) return false; return R.methodCat === "DEC" ? !!P.dec : (P.rounds || []).indexOf(R.round) !== -1; }
  if (market === "METHRDS") return R.win === P.side && R.methodCat === P.methodCat && (P.rounds || []).indexOf(R.round) !== -1;
  if (market === "DBLMETH") return R.win === P.side && (P.methods || []).indexOf(R.methodCat) !== -1;
  return false;
}
function btGradeStatus(market, P, R) {
  if (R.isNC) return "void";
  if (R.isDraw && market === "ML") return "void";
  return btGradeWin(market, P, R, R.round) ? "won" : "lost";
}
function btGradeParlay(b, events) {
  const legs = b.legs || [];
  const legStatuses = legs.map((l) => {
    const nm = btMatchNames(l.match);
    if (!nm) return "pending";
    const R = btResolveResult(events, b.evSlug, nm[0], nm[1]);
    return R ? btGradeStatus(l.market, l.params || {}, R) : "pending";
  });
  const liveIdx = legs.map((l, i) => i).filter((i) => legStatuses[i] !== "void");
  // Mirrors the client's btDeriveParlay: only reprice off the raw legs once one has
  // ACTUALLY voided. Otherwise this naive recombination almost never matches the
  // user's real quoted price (books apply their own vig/rounding to a parlay, not
  // a pure multiply of the leg prices), which made every ordinary parlay look like
  // it had a voided leg on someone's public profile.
  const anyVoided = liveIdx.length !== legs.length;
  const effOdds = anyVoided ? (liveIdx.length ? btCombineOdds(liveIdx.map((i) => legs[i].odds)) : null) : null;
  const legsIn = liveIdx.filter((i) => legStatuses[i] !== "pending").length;
  const legsLive = liveIdx.length;
  const base = { legStatuses, legsIn, legsLive };
  if (!liveIdx.length) return Object.assign({ status: "void", clv: null, effOdds: null }, base);
  if (liveIdx.some((i) => legStatuses[i] === "lost")) return Object.assign({ status: "lost", clv: null, effOdds }, base);
  if (liveIdx.every((i) => legStatuses[i] === "won")) return Object.assign({ status: "won", clv: null, effOdds }, base);
  return Object.assign({ status: "pending", clv: null, effOdds }, base);
}
// The frozen grade if present, else graded live from the feeds. null while still pending.
function btEffectiveGrade(b, events, closing) {
  if (b && b.graded && ["won", "lost", "push", "void"].indexOf(b.graded.status) !== -1) return b.graded;
  if (!b || b.kind !== "tracked") return null;
  if (b.market === "PARLAY") return btGradeParlay(b, events);
  const nm = btMatchNames(b.match);
  if (!nm) return null;
  const R = btResolveResult(events, b.evSlug, nm[0], nm[1]);
  if (!R) return null;
  const status = btGradeStatus(b.market, b.params || {}, R);
  let clv = null;
  if (b.priced && b.clvOk !== false && b.closeSide) {
    const close = btCloseFor(closing, nm[0], nm[1], b.closeSide);
    if (close != null) clv = btClvPts(b.odds, close);
  }
  return { status, clv, effOdds: null };
}
// Combined result set: finalized archive (pickem-results) + live/recent event feeds, so
// a bet reflects mid-card and not only once the archive is emitted at card end.
async function btLoadResultEvents(env, url) {
  const out = [];
  const res = await loadResults(env, url);
  for (const ev of (res.events || [])) out.push({ slug: ev.slug, bouts: ev.bouts || [] });
  for (const p of ["/data/event.json", "/data/event-recent.json"]) {
    const feed = await loadAssetJson(env, url, p);
    for (const ev of ((feed && feed.data) || [])) {
      const bouts = (ev.bouts || []).map(boutToResult).filter(Boolean);
      if (bouts.length) out.push({ slug: ev.slug, bouts });
    }
  }
  return out;
}
function btOutcome(b, events, closing) {
  const g = btEffectiveGrade(b, events, closing);
  if (!g || ["won", "lost", "push", "void"].indexOf(g.status) === -1) return null;
  const odds = (typeof g.effOdds === "number" ? g.effOdds : b.odds);
  const stake = typeof b.stake === "number" ? b.stake : 0;
  const profit = g.status === "won" ? stake * (odds > 0 ? odds / 100 : 100 / -odds)
    : g.status === "lost" ? -stake : 0;
  return { status: g.status, clv: (typeof g.clv === "number" ? g.clv : null), stake, profit };
}
// Same aggregation the client's btStats does, off the effective (frozen-or-live) grades.
function btUserStats(bets, events, closing) {
  const st = (bets || []).map((b) => btOutcome(b, events, closing)).filter(Boolean);
  if (!st.length) return null;
  const w = st.filter((o) => o.status === "won").length;
  const l = st.filter((o) => o.status === "lost").length;
  const staked = st.filter((o) => o.status !== "push" && o.status !== "void").reduce((s, o) => s + o.stake, 0);
  const units = st.reduce((s, o) => s + o.profit, 0);
  const clvs = st.filter((o) => o.clv != null);
  return {
    n: st.length, w, l,
    roi: staked ? (units / staked * 100) : null,
    units,
    avgClv: clvs.length ? clvs.reduce((s, o) => s + o.clv, 0) / clvs.length : null,
    clvN: clvs.length,
  };
}

async function handleBetsLeaderboard(request, env, url) {
  const s = await betsSession(request, env);
  if (!s) return json({ error: "unauthorized" }, 401);
  const tab = { clv: "clv", roi: "roi", units: "units" }[url.searchParams.get("tab")] || "units";
  // Time filter on bet placement time (b.ts), matching the history range chips.
  const BT_RANGE_DAYS = { "7d": 7, "30d": 30, "6m": 182, "12m": 365, all: null };
  const rangeKey = url.searchParams.get("range") || "all";
  const days = BT_RANGE_DAYS[rangeKey];
  const cutoff = (typeof days === "number" && days > 0) ? Date.now() - days * 864e5 : 0;
  // Load the result + closing-odds feeds once, then grade every user's bets on read.
  const [events, closing, keys] = await Promise.all([
    btLoadResultEvents(env, url), loadClosingOdds(env, url), listAllKeys(env, "bt:"),
  ]);
  const rows = [];
  await Promise.all(keys.map(async (k) => {
    const email = k.slice(3);                           // strip "bt:"
    const name = await getDisplayName(env, email);
    if (!name) return;                                  // no display name -> off the board
    let bets = await btGetBets(env, email);
    if (cutoff) bets = bets.filter((b) => (b.ts || b.createdAt || 0) >= cutoff);
    const stats = btUserStats(bets, events, closing);
    if (!stats) return;                                 // no settled verified bets in range
    rows.push({
      name, w: stats.w, l: stats.l, n: stats.n,
      clv: btRound1(stats.avgClv), clvN: stats.clvN,
      roi: btRound1(stats.roi), units: btRound1(stats.units),
    });
  }));
  const ranked = rows.filter((r) => r[tab] != null).sort((a, b) => b[tab] - a[tab]);
  ranked.forEach((r, i) => { r.rank = i + 1; });
  const myName = await getDisplayName(env, s.email);
  const me = myName ? (ranked.find((r) => r.name === myName) || null) : null;
  return json({ tab, range: rangeKey, rows: ranked.slice(0, 100), me });
}

// Public (subscriber) profile: one player's verified settled bets, by display name.
async function handleBetsPlayer(request, env, url) {
  const s = await betsSession(request, env);
  if (!s) return json({ error: "unauthorized" }, 401);
  const name = (url.searchParams.get("name") || "").trim();
  if (!name) return json({ error: "missing name" }, 400);
  const email = await env.PICKS.get("nm:" + name.toLowerCase());
  if (!email) return json({ error: "not found" }, 404);
  const bets = await btGetBets(env, email);
  const [events, closing] = await Promise.all([btLoadResultEvents(env, url), loadClosingOdds(env, url)]);
  const stats = btUserStats(bets, events, closing);
  // Grade each bet on read: a settled (frozen-or-live) grade puts it in the settled
  // list; anything still unresolved is an open bet.
  const grade = (b) => btEffectiveGrade(b, events, closing);
  const isSettled = (b) => { const g = grade(b); return !!g && ["won", "lost", "push", "void"].indexOf(g.status) !== -1; };
  const byNewest = (a, b) => (b.ts || b.createdAt || 0) - (a.ts || a.createdAt || 0);
  const common = (b) => ({
    pick: b.pick || "", match: b.match || "", market: b.market || "",
    fightId: b.fightId || null, evSlug: b.evSlug || null,
    side: (b.params && b.params.side != null) ? b.params.side : null,
    // Parlay legs — same shape btLegAvHTML/legsHTML expect on the owner's own
    // history, so the profile view (btPlayerBetHTML/btPlayerPendingHTML) can
    // render each leg instead of just the combined pick line.
    legs: b.market === "PARLAY" ? (b.legs || null) : null,
    book: b.book || null,
  });
  const settled = (bets || [])
    .filter((b) => b.kind === "tracked" && isSettled(b))
    .sort(byNewest)
    .slice(0, 200)
    .map((b) => {
      const g = grade(b), o = btOutcome(b, events, closing);
      return Object.assign(common(b), {
        odds: (g && typeof g.effOdds === "number") ? g.effOdds : b.odds,
        stake: b.stake, status: g.status,
        profit: btRound2(o ? o.profit : 0),
        clv: (g && typeof g.clv === "number") ? btRound1(g.clv) : null,
        legStatuses: (g && g.legStatuses) || null,
        ts: b.ts || b.createdAt || 0,
      });
    });
  // Open bets: tracked bets not yet settled. Lets a viewer see what this player is
  // currently on. No result/CLV yet, so just the pick.
  const pending = (bets || [])
    .filter((b) => b.kind === "tracked" && !isSettled(b))
    .sort(byNewest)
    .slice(0, 100)
    .map((b) => {
      const g = b.market === "PARLAY" ? grade(b) : null;
      return Object.assign(common(b), {
        odds: b.odds, stake: b.stake, ts: b.ts || b.createdAt || 0,
        legStatuses: (g && g.legStatuses) || null,
        legsIn: (g && g.legsIn) || 0, legsLive: (g && g.legsLive) || (b.legs || []).length,
      });
    });
  return json({
    name,
    stats: stats ? {
      w: stats.w, l: stats.l, n: stats.n,
      roi: btRound1(stats.roi), units: btRound1(stats.units),
      avgClv: btRound1(stats.avgClv), clvN: stats.clvN,
    } : null,
    bets: settled,
    pending,
  });
}

async function handleBetsSettle(request, env) {
  const s = await betsSession(request, env);
  if (!s) return json({ error: "unauthorized" }, 401);
  const body = await readBody(request);
  const id = body.id;
  // Normalize common spellings so a client/label mismatch grades instead of erroring
  // (win->won, loss/lose->lost, tie->push, draw/nc->void, …). If it's still unrecognized,
  // put the ACTUAL value in the error so the popup names what was wrong — this endpoint
  // was returning a bare "bad status", which told us nothing about the offending value.
  const STATUS_ALIAS = {
    won: "won", win: "won", w: "won",
    lost: "lost", loss: "lost", lose: "lost", l: "lost",
    push: "push", p: "push", tie: "push",
    void: "void", voided: "void", nc: "void", "no contest": "void", draw: "void", d: "void",
  };
  const status = STATUS_ALIAS[String(body.status == null ? "" : body.status).trim().toLowerCase()] || null;
  if (!status) return json({ error: 'bad status: "' + String(body.status).slice(0, 40) + '"' }, 400);
  const list = await btGetBets(env, s.email);
  const b = list.find((x) => x.id === id);
  if (!b) return json({ error: "not found" }, 404);
  if (b.kind !== "manual") return json({ error: "Tracked bets grade automatically." }, 403);
  b.status = status;
  await btPutBets(env, s.email, list);
  return json({ ok: true });
}

// `editable` is a SNAPSHOT taken once at log time (clvOk for a single, always
// true for a parlay) — it never gets re-checked against the clock. That let
// either endpoint below rewrite or erase a bet at ANY time before it's fully
// decided, including well after its segment actually started: log a single
// early (editable:true), then edit the odds/stake — or delete it outright —
// after watching it go live, which is exactly the CLV-laundering / bad-bet-
// erasing the comments below describe as prevented. A parlay was worse: only
// the OVERALL status has to still read "pending" (every leg won, or none
// decided yet), so a 2-leg parlay with leg 1 already WON could still have its
// stake bumped up right before leg 2 goes off — de-risked, then sized up.
// Re-derives the real lock from the current feeds instead of trusting the
// stored flag: locked once ANY constituent fight's segment has started OR has
// itself been individually decided (even if the parlay as a whole hasn't).
// Manual (self-reported) bets have no real close to protect and are exempt.
async function btEditLocked(env, url, b) {
  if (b.kind !== "tracked") return false;
  const now = Date.now();
  const legFightIds = b.market === "PARLAY" ? (b.legs || []).map((l) => l.fightId) : [b.fightId];
  for (const fid of legFightIds) {
    const hit = await btFindBout(env, url, String(fid || ""));
    if (!hit) continue;   // aged out of the feed — can't re-check this leg, don't block on it
    const segAt = Date.parse(hit.segAt);
    if (isFinite(segAt) && now >= segAt) return true;
    if (await btBoutDecided(env, url, hit)) return true;
  }
  return false;
}

// Edit the price / stake while still pending and before the segment locks. Same
// gate as delete, and for the same reason: once the close is knowable, letting
// someone rewrite the price they "got" would manufacture CLV out of thin air.
// Only odds and stake are editable — never the bout, market or selection (that
// would be a different bet, logged at a different time).
async function handleBetsEdit(request, env, url) {
  const s = await betsSession(request, env);
  if (!s) return json({ error: "unauthorized" }, 401);
  const { id, odds, stake, book } = await readBody(request);
  const list = await btGetBets(env, s.email);
  const b = list.find((x) => x.id === id);
  if (!b) return json({ error: "not found" }, 404);
  if (b.editable === false) return json({ error: "This bet is locked in." }, 403);
  if (b.status && b.status !== "pending") return json({ error: "That bet has already settled." }, 403);
  if (await btEditLocked(env, url, b)) return json({ error: "That segment has already started — this bet is locked in." }, 403);
  const o = parseInt(odds, 10);
  if (!isFinite(o) || o === 0) return json({ error: "Enter the odds you got." }, 400);
  b.odds = o;
  b.stake = Math.max(0.1, Math.min(1000, Number(stake) || b.stake));
  if (book !== undefined) b.book = String(book || "").slice(0, 40).trim();
  b.editedAt = Date.now();
  await btPutBets(env, s.email, list);
  return json({ ok: true, bet: b });
}

// Delete while still pending and before the segment locks. After that the close
// is knowable, so removing a losing CLV bet would launder the number.
async function handleBetsDelete(request, env, url) {
  const s = await betsSession(request, env);
  if (!s) return json({ error: "unauthorized" }, 401);
  const { id } = await readBody(request);
  const list = await btGetBets(env, s.email);
  const b = list.find((x) => x.id === id);
  if (!b) return json({ error: "not found" }, 404);
  if (b.editable === false) return json({ error: "This bet is locked in." }, 403);
  // Deliberately no b.status check here (unlike edit) — a self-reported bet
  // could always be deleted after being marked won/lost, and that's unchanged.
  // A TRACKED bet that's already decided is still caught: its segment
  // necessarily started for it to have a result, so btEditLocked catches it.
  if (await btEditLocked(env, url, b)) return json({ error: "That segment has already started — this bet is locked in." }, 403);
  await btPutBets(env, s.email, list.filter((x) => x.id !== id));
  return json({ ok: true });
}

// FOUNDER-ONLY, one-time hand fix. The winner-select-reset bug (fixed the same
// day this shipped) let a single-fighter bet silently record the WRONG side if
// the Market dropdown was switched after already picking a winner — the pick
// text and params.side agreed with each other, just both wrong. A bet like
// that is otherwise stuck forever once its fight is decided: the normal edit
// endpoint only ever touches odds/stake (never the selection, by design — "that
// would be a different bet"), and btEditLocked correctly refuses to edit OR
// delete a bet whose fight has already been decided, which this one now is.
// Scoped narrowly on purpose — flips a single/METHOD-family bet's side and
// rewrites its pick text to match, nothing else, and only for the caller's own
// bets (email comes from THEIR session, never the request body) — this is a
// scalpel for the one bug class above, not a general "edit anything" backdoor.
async function handleAdminFixBetSide(request, env) {
  const s = await betsSession(request, env);
  if (!s || !FOUNDER_EMAILS.has(s.email)) return json({ error: "unauthorized" }, 401);
  const { id, side, pick } = await readBody(request);
  if (!id) return json({ error: "missing id" }, 400);
  const sd = side === 2 ? 2 : side === 1 ? 1 : null;
  if (sd == null) return json({ error: "side must be 1 or 2" }, 400);
  const list = await btGetBets(env, s.email);
  const b = list.find((x) => x.id === id);
  if (!b) return json({ error: "not found" }, 404);
  if (b.kind !== "tracked" || b.market === "PARLAY") {
    return json({ error: "this only fixes a single tracked bet's side, not a parlay or a self-reported bet" }, 400);
  }
  const before = { pick: b.pick, side: b.params && b.params.side, graded: b.graded || null };
  b.params = Object.assign({}, b.params, { side: sd });
  if (typeof pick === "string" && pick.trim()) b.pick = pick.trim().slice(0, 160);
  // The bet's outcome was frozen server-side under the WRONG side (write-once by
  // design — see handleBetsGrade — so it would otherwise never re-derive). Flipping
  // the side without clearing this leaves the client short-circuiting straight to
  // the stale frozen grade (btDeriveAll: "if (b.graded && b.graded.status) { ...
  // return; }") and still showing the old result forever. Delete it so the next
  // load re-grades from scratch against the corrected side, and re-freezes on its own.
  delete b.graded;
  b.fixedAt = Date.now();
  await btPutBets(env, s.email, list);
  return json({ ok: true, before, bet: b });
}
