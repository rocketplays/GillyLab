#!/usr/bin/env node
/* Regenerates worker/scorecard-data.js — the internal model-performance scorecard
 * embedded into the Worker so the founder-only /scorecard page can render WITHOUT
 * serving the raw prediction files (predictions-*.json) to subscribers.
 *
 * Sources (produced by scripts/grade-predictions.cjs):
 *   - data/predictions-scorecard.json  → aggregate CLV + calibration metrics
 *   - data/predictions-graded.json     → per-fight graded records
 *
 * Safe by design: if the scorecard can't be parsed, the existing
 * scorecard-data.js is left untouched and the script still exits 0, so a hiccup
 * never breaks the odds workflow. Run it after grade-predictions.cjs.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'worker', 'scorecard-data.js');

function readJSON(p) { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch (e) { return null; } }

function main() {
  const scorecard = readJSON(path.join(ROOT, 'data', 'predictions-scorecard.json'));
  const gradedFile = readJSON(path.join(ROOT, 'data', 'predictions-graded.json'));
  if (!scorecard) { console.warn('gen-scorecard-data: no scorecard json — keeping existing file'); return; }

  // Slim per-fight rows for the table (drop internal ids/timestamps).
  const graded = ((gradedFile && gradedFile.graded) || []).map(g => ({
    event: g.event, a: g.a, b: g.b, winner: g.winner, method: g.method, round: g.round,
    aWon: g.aWon, rounds: g.rounds,
    modelOpen: g.modelOpen, modelClose: g.modelClose,
    marketOpen: g.marketOpen, marketClose: g.marketClose,
    leanA: g.leanA, clv: g.clv
  }));

  const out = { generatedAt: new Date().toISOString(), scorecard, graded };
  fs.writeFileSync(OUT,
    '// AUTO-GENERATED by scripts/gen-scorecard-data.cjs — do not edit by hand.\n' +
    'export default ' + JSON.stringify(out, null, 2) + ';\n');
  console.log('scorecard-data.js: nGraded %d · CLV hit %s', scorecard.nGraded,
    scorecard.clv && scorecard.clv.hitRate != null ? (scorecard.clv.hitRate * 100).toFixed(0) + '%' : 'n/a');
}
main();
