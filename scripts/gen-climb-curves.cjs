#!/usr/bin/env node
/* The Climb — attribute curves, anchored to the real division.
 *
 * Emits the CURVES table pasted into prototypes/the-climb.html. Run after
 * gen-climb-data.cjs; re-run when the division changes.
 *
 * WHY THIS EXISTS. The curves used to be hand-picked linear ramps (kd =
 * 0.1 + v*0.55). Measured against the real LW ladder, they were fantasy:
 *
 *     level 10 Power = 5.60 kd   -- 3.6x the best lightweight who has EVER fought
 *     level  1 Power = 0.65 kd   -- already ABOVE the division median (0.39)
 *
 * The whole curve sat off the end of the data. The sim was never trained on
 * those values, which is exactly why gains flattened past level 7: the model
 * was refusing to extrapolate, which is correct behaviour. It also meant the
 * top half of every attribute was inert, so spreading beat specialising --
 * arbitrage on my own bad mapping, not a fact about MMA.
 *
 * THE RULE NOW: level 0 is the division's worst, the division's BEST lands
 * around level 8.8, and level 10
 * is beyond anyone (+20% headroom). Every level is an interval the model has
 * actually seen.
 *
 * The anchors self-validate -- they land on the right names without being told:
 *     Power     -> Mauricio Ruffy      Pace      -> Max Holloway
 *     Grappling -> Charles Oliveira    Wrestling -> Mateusz Gamrot
 *     TD def    -> Ilia Topuria        Defense   -> Arman Tsarukyan
 *
 * SHAPE: value(t) = lo + (hi-lo) * t^k, k fitted so the curve passes through the
 * division's MEDIAN at the midpoint level. A right-skewed stat (elite power is
 * rare) yields k>1 and a convex curve; a flat one yields k~1. So the convexity
 * is the sport's, not a designer's guess -- Power comes out k=1.6 (convex),
 * strAcc k=1.0 (linear), because that is how lightweights are actually shaped.
 *
 * k is capped at 1.6. Uncapped, Power fits k=2.6 and levels 1-2 move kd by
 * 0.005 -- a point you spend for nothing. Convexity has to stop before it eats
 * the bottom of its own scale.
 */
'use strict';
const fs=require('fs'), path=require('path');
const ROOT=path.resolve(__dirname,'..');
const D=JSON.parse(fs.readFileSync(path.join(ROOT,'prototypes','climb-data.json'),'utf8'));
const S=D.FIGHTER_STATS;

const HEAD=1.20;   // level 10 = 20% beyond the division's best.
const KCAP=1.6;
const LEVELS=11;   // 0..10

const num=v=>{if(v==null)return null;const m=/(-?\d+(\.\d+)?)/.exec(String(v));return m?+m[1]:null;};
const vals=k=>D.ladder.map(f=>num(S[f.name]&&S[f.name][k])).filter(v=>v!=null&&isFinite(v)).sort((a,b)=>a-b);
const q=(a,p)=>{const i=(a.length-1)*p,lo=Math.floor(i),hi=Math.ceil(i);return lo===hi?a[lo]:a[lo]+(a[hi]-a[lo])*(i-lo);};

// Robust ceiling: the division's best, unless he's a small-sample freak.
// Drop the top value only if it exceeds 1.3x the second -- an outlier gate, not
// a hand-pick. It fires exactly once: Quillan Salkilld's 7.25 td/15min over 3
// fights, which would have set level 10 at 8.7 and made Gamrot look ordinary.
function ceilOf(a,dir){
  const s=dir==='down'?a.slice().reverse():a;
  const top=s[s.length-1], second=s[s.length-2];
  if(dir==='down') return (second>0&&top<second/1.3)?second:top;
  return (second>0&&top>second*1.3)?second:top;
}
const who=(key,v)=>{const m=D.ladder.find(f=>Math.abs(num(S[f.name]&&S[f.name][key])-v)<1e-9);return m?m.name:'?';};

function build(key,dir,isPct){
  const a=vals(key);
  const lo=dir==='down'?q(a,0.95):q(a,0.05);
  const best=ceilOf(a,dir), med=q(a,0.5);
  // Rates get headroom above the best. Percentages DON'T: they are bounded by
  // physics -- you cannot be 114% takedown-defensive -- so a 10 in tdDef is
  // Topuria's 95% and that is already the ceiling of the sport.
  const hi=isPct?best:(dir==='down'?best/HEAD:best*HEAD);
  const frac=Math.min(0.95,Math.max(0.05,(med-lo)/(hi-lo)));
  const k=Math.min(KCAP,Math.max(1.0,Math.log(frac)/Math.log(0.5)));
  const out=[];
  for(let v=0;v<LEVELS;v++){const t=v/(LEVELS-1);out.push(lo+(hi-lo)*Math.pow(t,k));}
  const r=x=>isPct?Math.round(x*10)/10:Math.round(x*1000)/1000;
  return {out:out.map(r),k:Math.round(k*100)/100,best:r(best),who:who(key,best)};
}
const SPEC=[['kd',0,0],['slpm',0,0],['strAcc',0,1],['strDef',0,1],['sapm',1,0],
            ['tdLanded',0,0],['tdAcc',0,1],['subAvg',0,0],['tdDef',0,1]];
const lines=[], report=[];
for(const [key,dn,pct] of SPEC){
  const b=build(key,dn?'down':'up',!!pct);
  lines.push('  '+key.padEnd(9)+': ['+b.out.join(', ')+'],');
  report.push('  '+key.padEnd(9)+' k='+b.k+'  lvl9='+b.best+' ('+b.who+')');
}
const js='// AUTO-GENERATED by scripts/gen-climb-curves.cjs -- do not hand-edit.\n'+
  '// level 0 = the division\'s worst, ~8.8 = its best, 10 = beyond anyone.\n'+
  'const CURVES = {\n'+lines.join('\n')+'\n};\n';
fs.writeFileSync(path.join(ROOT,'prototypes','climb-curves.txt'),js);
console.log(js);
console.log('anchors:');
console.log(report.join('\n'));
